class ApprovalStatus(str, Enum):
    """Status of a merchant review request."""
    PENDING = "PENDING"
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"


class ApprovalRequest(BaseModel):
    """Record representing a high-value or policy-flagged action awaiting merchant sign-off."""
    approval_id: str = Field(..., description="Unique approval request ID (e.g. app_req_12345)")
    payment_id: str = Field(..., description="Payment ID under review")
    customer_id: str = Field(..., description="Customer ID")
    amount: float = Field(..., ge=0.0, description="Transaction amount in INR")
    requested_action: RecoveryAction = Field(..., description="Action requested by AI")
    ai_reason: str = Field(..., description="AI diagnosis and recovery rationale")
    ai_confidence: float = Field(..., ge=0.0, le=1.0, description="AI confidence score")
    policy_reason: str = Field(..., description="Why policy engine required approval")
    status: ApprovalStatus = Field(default=ApprovalStatus.PENDING, description="PENDING, APPROVED, or REJECTED")
    created_at: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="ISO 8601 creation timestamp",
    )
    reviewed_at: Optional[str] = Field(default=None, description="ISO 8601 review timestamp")
    reviewer: Optional[str] = Field(default=None, description="Identifier or name of the merchant reviewer")
    notes: Optional[str] = Field(default=None, description="Optional merchant review comments")


class AuditLogEntry(BaseModel):
    """Immutable audit trail record for compliance and inspection."""
    event_id: str = Field(..., description="Unique event identifier")
    timestamp: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="ISO 8601 event timestamp",
    )
    payment_id: str = Field(..., description="Target payment ID")
    action: Optional[str] = Field(default=None, description="Recovery action involved")
    event_type: str = Field(..., description="Event classification (PAYMENT_DETECTED, AI_ANALYZED, etc.)")
    status: str = Field(default="INFO", description="Event status: SUCCESS, FAILED, BLOCKED, etc.")
    message: str = Field(default="", description="Descriptive event message")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Structured event payload")
    recovery_id: Optional[str] = Field(default=None, description="Razorpay recovery ID if available")

    # Backward compatibility property/alias
    @property
    def log_id(self) -> str:
        return self.event_id


