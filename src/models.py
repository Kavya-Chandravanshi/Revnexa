"""Core data models and enums for RecoverPay AI.

Defines Pydantic schemas for payment records, recovery actions, failure reasons,
and structured exchange between AI and deterministic layers.
"""

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field, field_validator, model_validator


class PaymentStatus(str, Enum):
    """Lifecycle status of a payment transaction."""
    FAILED = "FAILED"
    AT_RISK = "AT_RISK"
    PROCESSING = "PROCESSING"
    RECOVERED = "RECOVERED"
    EXPIRED = "EXPIRED"
    ABANDONED = "ABANDONED"


class FailureReason(str, Enum):
    """Categorized Razorpay failure codes and root causes."""
    BANK_SERVER_DOWN = "BANK_SERVER_DOWN"
    NETWORK_TIMEOUT = "NETWORK_TIMEOUT"
    AUTHENTICATION_FAILED = "AUTHENTICATION_FAILED"
    INSUFFICIENT_FUNDS = "INSUFFICIENT_FUNDS"
    PAYMENT_LIMIT_EXCEEDED = "PAYMENT_LIMIT_EXCEEDED"
    CARD_EXPIRED = "CARD_EXPIRED"
    INVALID_CARD_DETAILS = "INVALID_CARD_DETAILS"
    SUSPECTED_FRAUD = "SUSPECTED_FRAUD"


class RecoveryAction(str, Enum):
    """Allowed recovery strategies mandated by system design."""
    RETRY = "RETRY"
    PAYMENT_LINK = "PAYMENT_LINK"
    REMINDER = "REMINDER"
    INCENTIVE = "INCENTIVE"
    ESCALATE = "ESCALATE"
    STOP = "STOP"


class ProductCategory(str, Enum):
    """Product/service category for risk and margin context."""
    SAAS = "SAAS"
    ECOMMERCE = "ECOMMERCE"
    B2B_SERVICES = "B2B_SERVICES"
    EDTECH = "EDTECH"
    HEALTHCARE = "HEALTHCARE"


class PaymentRecord(BaseModel):
    """Single payment transaction record with customer context.
    
    Guarantees internal consistency between transaction amounts,
    customer payment histories, and failure metadata.
    """
    payment_id: str = Field(
        ...,
        description="Unique Razorpay-style payment identifier (e.g. pay_synth_12345)",
    )
    customer_id: str = Field(
        ...,
        description="Customer identifier (e.g. cust_synth_12345)",
    )
    customer_name: str = Field(
        ...,
        description="Customer full name for notifications and display",
    )
    customer_email: str = Field(
        ...,
        description="Customer email address",
    )
    customer_phone: Optional[str] = Field(
        default=None,
        description="Customer phone number for SMS/WhatsApp/link delivery",
    )
    order_id: str = Field(
        ...,
        description="Unique order identifier (e.g. order_synth_12345)",
    )
    amount: float = Field(
        ...,
        gt=0,
        description="Transaction amount in positive decimal INR",
    )
    currency: str = Field(
        default="INR",
        description="Three-letter ISO currency code, defaulting to INR",
    )
    payment_status: PaymentStatus = Field(
        default=PaymentStatus.FAILED,
        description="Current state of payment record",
    )
    failure_reason: FailureReason = Field(
        ...,
        description="Standardized error category for the failed transaction",
    )
    error_description: Optional[str] = Field(
        default=None,
        description="Raw error message as returned by gateway or issuing bank",
    )
    retry_count: int = Field(
        default=0,
        ge=0,
        description="Number of automated or manual recovery attempts already made",
    )
    customer_previous_payments: int = Field(
        default=0,
        ge=0,
        description="Count of historical successful payments by this customer",
    )
    customer_previous_failures: int = Field(
        default=0,
        ge=0,
        description="Count of historical failed payments by this customer",
    )
    customer_total_spend: float = Field(
        default=0.0,
        ge=0.0,
        description="Cumulative historical revenue generated by this customer in INR",
    )
    days_since_last_success: Optional[int] = Field(
        default=None,
        ge=0,
        description="Days elapsed since the customer's last successful transaction",
    )
    product_category: ProductCategory = Field(
        ...,
        description="Product vertical to guide incentive margins and outreach tone",
    )
    created_at: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="ISO 8601 creation timestamp",
    )

    @field_validator("currency")
    @classmethod
    def validate_currency(cls, v: str) -> str:
        if v.upper() != "INR":
            raise ValueError(f"Only INR currency is currently supported in this MVP, got {v}")
        return v.upper()

    @model_validator(mode="after")
    def validate_customer_history_consistency(self) -> "PaymentRecord":
        """Enforces logical coherence between payments, spend, and recency."""
        # If customer has never paid before, total spend must be 0 and days_since must be None
        if self.customer_previous_payments == 0:
            if self.customer_total_spend > 0.0:
                raise ValueError(
                    f"Inconsistent customer history: customer_previous_payments is 0, "
                    f"but customer_total_spend is {self.customer_total_spend}"
                )
            if self.days_since_last_success is not None:
                raise ValueError(
                    f"Inconsistent customer history: customer_previous_payments is 0, "
                    f"but days_since_last_success is {self.days_since_last_success}"
                )
        else:
            # If customer has previous payments, total spend must be positive
            if self.customer_total_spend <= 0.0:
                raise ValueError(
                    f"Inconsistent customer history: customer_previous_payments is {self.customer_previous_payments}, "
                    f"but customer_total_spend is {self.customer_total_spend}"
                )
            if self.days_since_last_success is None:
                raise ValueError(
                    f"Inconsistent customer history: customer_previous_payments is {self.customer_previous_payments}, "
                    "but days_since_last_success is None"
                )

        return self


