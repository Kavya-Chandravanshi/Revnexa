class RecoveryRecommendation(BaseModel):
    """Proposal emitted by the AI Agent for merchant/policy review."""
    action: RecoveryAction = Field(
        ...,
        description="Recommended action: RETRY, PAYMENT_LINK, REMINDER, INCENTIVE, ESCALATE, STOP",
    )
    confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Model confidence score between 0.0 and 1.0",
    )
    discount_pct: float = Field(
        default=0.0,
        ge=0.0,
        le=100.0,
        description="Suggested percentage discount if action is INCENTIVE",
    )
    reasoning: str = Field(
        ...,
        description="Clear, explainable reasoning describing why this recovery path was selected",
    )
    customer_message: Optional[str] = Field(
        default=None,
        description="Tailored notification copy drafted for the customer",
    )


class AIRecommendation(BaseModel):
    """Structured recommendation produced by the AI Recovery Agent (Gemini or Fallback)."""
    action: RecoveryAction = Field(
        ...,
        description="Recommended recovery action: RETRY, PAYMENT_LINK, REMINDER, INCENTIVE, ESCALATE, STOP",
    )
    confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Confidence score between 0.0 and 1.0 reflecting strength of evidence",
    )
    reason: str = Field(
        ...,
        description="Concise, human-readable rationale grounded in actual transaction context",
    )
    expected_recovery: float = Field(
        ...,
        ge=0.0,
        description="Estimated potential recovered revenue in INR (cannot be negative)",
    )
    risk_level: str = Field(
        default="LOW",
        description="Risk classification: LOW, MEDIUM, HIGH, or CRITICAL",
    )
    proposed_discount_pct: float = Field(
        default=0.0,
        ge=0.0,
        le=100.0,
        description="Proposed discount percentage when action is INCENTIVE (cannot be negative)",
    )
    requires_approval_recommendation: bool = Field(
        default=False,
        description="Advisory flag indicating whether this recommendation should require merchant approval",
    )
    agent_mode: str = Field(
        default="fallback",
        description="Generation source: 'gemini' or 'fallback'",
    )
    model_name: Optional[str] = Field(
        default=None,
        description="Model name if generated by LLM (e.g. gemini-2.5-flash)",
    )



class PolicyDecisionType(str, Enum):
    """Discrete decision outcome from deterministic policy engine."""
    ALLOWED = "ALLOWED"
    REQUIRES_APPROVAL = "REQUIRES_APPROVAL"
    BLOCKED = "BLOCKED"


class PolicyResult(BaseModel):
    """Deterministic policy evaluation result for a recovery action."""
    decision: PolicyDecisionType = Field(
        ...,
        description="ALLOWED, REQUIRES_APPROVAL, or BLOCKED",
    )
    allowed: bool = Field(
        ...,
        description="True if action can proceed (either immediately or after approval)",
    )
    requires_approval: bool = Field(
        ...,
        description="True if human-in-the-loop merchant approval is strictly required",
    )
    reason: str = Field(
        ...,
        description="Human-readable explanation of why the action was allowed, blocked, or flagged",
    )
    effective_discount: float = Field(
        default=0.0,
        ge=0.0,
        description="Deterministically calculated discount in INR",
    )
    max_allowed_discount: float = Field(
        default=0.0,
        ge=0.0,
        description="Maximum permissible discount in INR under policy caps",
    )
    policy_codes: List[str] = Field(
        default_factory=list,
        description="Standard policy audit codes applied during evaluation",
    )
    payment_id: Optional[str] = Field(
        default=None,
        description="Target payment identifier",
    )
    action: Optional[RecoveryAction] = Field(
        default=None,
        description="The action being evaluated",
    )
    final_payable_amount: Optional[float] = Field(
        default=None,
        description="Exact rupee amount to be charged after discount is deducted",
    )


class PolicyDecision(BaseModel):
    """Deterministic validation result produced by the Policy Engine."""
    status: str = Field(
        ...,
        description="AUTO_APPROVED, REQUIRES_APPROVAL, or BLOCKED",
    )
    approved_action: Optional[RecoveryAction] = Field(
        default=None,
        description="Final action allowed by policy (may override AI if blocked/escalated)",
    )
    approved_discount_pct: float = Field(
        default=0.0,
        ge=0.0,
        description="Clamped incentive percentage strictly conforming to policy caps",
    )
    final_payable_amount: float = Field(
        ...,
        ge=0.0,
        description="Exact rupee amount payable after any approved incentive",
    )
    violations: List[str] = Field(
        default_factory=list,
        description="List of policy rule violations detected, if any",
    )
    requires_merchant_approval: bool = Field(
        default=False,
        description="True if human-in-the-loop merchant approval is strictly required",
    )
    explanation: str = Field(
        default="",
        description="Summary of policy rules applied and any safety overrides",
    )



